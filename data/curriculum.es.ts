// Data mentah kurikulum Bahasa Spanyol: 25 unit / 125 pelajaran dengan struktur
// yang sejajar dengan kurikulum Bahasa Inggris. Bahasa Spanyol memakai huruf
// Latin, jadi (seperti Inggris) kolom "cara baca" diisi ejaan kata itu sendiri
// dalam huruf a-z polos — tanpa tanda aksen dan tanpa tanda baca — dan DIHITUNG
// OTOMATIS dari kata aslinya lewat `reading()` di bawah (ñ ditulis "ny", mis.
// "año" -> "anyo"). Jadi data cukup menulis kata Spanyol-nya sekali saja, dan
// ejaan untuk latihan susun-huruf / ketik tidak mungkin salah ketik.
//
// Format helper: W("kata Spanyol", "arti Indonesia", "contoh?", "arti contoh?").
// Arti Indonesia SATU saja per kata (keterangan boleh di dalam kurung, akan jadi
// catatan kecil). Kata benda ditulis tanpa kata sandang (el/la) supaya latihan
// mengetik tidak terasa kaku; jenis kelamin kata muncul di contoh kalimat.
function reading(es: string): string {
  return es
    .toLowerCase()
    .replace(/ñ/g, "ny")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z ]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

